-- 9. FAQ TABLE
CREATE TABLE IF NOT EXISTS public.faqs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id bigint REFERENCES public.cameras(id) ON DELETE CASCADE,
  question text NOT NULL,
  answer text NOT NULL,
  display_order int DEFAULT 0,
  is_active boolean DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 10. REVIEWS TABLE (MODERATED)
CREATE TABLE IF NOT EXISTS public.reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  camera_id bigint REFERENCES public.cameras(id) ON DELETE CASCADE,
  customer_name text NOT NULL,
  customer_phone_masked text,
  rating int NOT NULL DEFAULT 5,
  comment text NOT NULL,
  status text DEFAULT 'approved',
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 11. INDEXES
CREATE INDEX IF NOT EXISTS idx_cameras_slug ON public.cameras(slug);
CREATE INDEX IF NOT EXISTS idx_cameras_status ON public.cameras(status);
CREATE INDEX IF NOT EXISTS idx_camera_variants_sku ON public.camera_variants(sku);
CREATE INDEX IF NOT EXISTS idx_stock_movements_sku ON public.stock_movements(sku);
