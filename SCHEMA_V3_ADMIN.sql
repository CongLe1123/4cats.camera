-- 6. STOCK MOVEMENTS AUDIT LOG
CREATE TABLE IF NOT EXISTS public.stock_movements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL,
  camera_id bigint REFERENCES public.cameras(id) ON DELETE SET NULL,
  branch_name text NOT NULL,
  quantity_change int NOT NULL,
  quantity_after int NOT NULL,
  reason text NOT NULL,
  reference_order_id text,
  staff_email text,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 7. PROMOTIONS / COUPONS TABLE
CREATE TABLE IF NOT EXISTS public.promotions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code text UNIQUE,
  title text NOT NULL,
  customer_label text,
  description text,
  discount_type text NOT NULL DEFAULT 'percentage',
  discount_value numeric NOT NULL,
  min_order_value numeric DEFAULT 0,
  start_at timestamp with time zone,
  end_at timestamp with time zone,
  is_active boolean DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 8. REDIRECTS (301 PERMANENT REDIRECTS FOR LEGACY URLS)
CREATE TABLE IF NOT EXISTS public.url_redirects (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_path text NOT NULL UNIQUE,
  to_path text NOT NULL,
  status_code int DEFAULT 301,
  is_active boolean DEFAULT true,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

