-- ==============================================================================
-- 4cats Camera — Schema V3: Genuine Brand-New Camera E-Commerce Architecture
-- ==============================================================================
-- Architecture: PRODUCT (Model) -> PRODUCT VARIANTS / SKUs -> STOCK (Branch Level)
-- NO LONGER designed around used-camera condition %, shutter count, or cosmetic grade.
-- ==============================================================================

-- 1. EXTENSIONS & UUID
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. ENSURE CAMERAS TABLE HAS NEW CAMERA ARCHITECTURE COLUMNS
ALTER TABLE IF EXISTS public.cameras 
  ADD COLUMN IF NOT EXISTS slug text,
  ADD COLUMN IF NOT EXISTS short_description text,
  ADD COLUMN IF NOT EXISTS beginner_summary text,
  ADD COLUMN IF NOT EXISTS strengths text[] DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS limitations text[] DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS use_cases text[] DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS technical_specs jsonb DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS compatible_accessories jsonb DEFAULT '[]',
  ADD COLUMN IF NOT EXISTS search_aliases text[] DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS is_published boolean DEFAULT true,
  ADD COLUMN IF NOT EXISTS is_featured boolean DEFAULT false,
  ADD COLUMN IF NOT EXISTS featured_section text DEFAULT 'featured',
  ADD COLUMN IF NOT EXISTS featured_order int DEFAULT 0,
  ADD COLUMN IF NOT EXISTS seo_title text,
  ADD COLUMN IF NOT EXISTS seo_description text,
  ADD COLUMN IF NOT EXISTS status text DEFAULT 'published',
  ADD COLUMN IF NOT EXISTS updated_at timestamp with time zone DEFAULT timezone('utc'::text, now());

-- 3. ENSURE CAMERA_VARIANTS TABLE HAS SKU, PRICING & STOCK COLUMNS
ALTER TABLE IF EXISTS public.camera_variants
  ADD COLUMN IF NOT EXISTS sku text,
  ADD COLUMN IF NOT EXISTS color text,
  ADD COLUMN IF NOT EXISTS color_label text,
  ADD COLUMN IF NOT EXISTS color_hex text,
  ADD COLUMN IF NOT EXISTS kit_type text DEFAULT 'Body only',
  ADD COLUMN IF NOT EXISTS kit_label text DEFAULT 'Thân máy (Body only)',
  ADD COLUMN IF NOT EXISTS included_lens text,
  ADD COLUMN IF NOT EXISTS compare_at_price numeric,
  ADD COLUMN IF NOT EXISTS cost_price numeric,
  ADD COLUMN IF NOT EXISTS stock_quantity int DEFAULT 0,
  ADD COLUMN IF NOT EXISTS branch_stock jsonb DEFAULT '{"Cầu Giấy": 0, "Thanh Xuân": 0}',
  ADD COLUMN IF NOT EXISTS warranty text DEFAULT '12 tháng chính hãng',
  ADD COLUMN IF NOT EXISTS weight_grams int,
  ADD COLUMN IF NOT EXISTS variant_images text[] DEFAULT '{}',
  ADD COLUMN IF NOT EXISTS status text DEFAULT 'active';

-- 4. BANNERS TABLE ENHANCEMENTS FOR SCHEDULING & MOBILE
ALTER TABLE IF EXISTS public.banners
  ADD COLUMN IF NOT EXISTS internal_name text,
  ADD COLUMN IF NOT EXISTS subtitle text,
  ADD COLUMN IF NOT EXISTS mobile_image text,
  ADD COLUMN IF NOT EXISTS start_at timestamp with time zone,
  ADD COLUMN IF NOT EXISTS end_at timestamp with time zone,
  ADD COLUMN IF NOT EXISTS is_active boolean DEFAULT true,
  ADD COLUMN IF NOT EXISTS status text DEFAULT 'active';

-- 5. BRANCHES TABLE
CREATE TABLE IF NOT EXISTS public.branches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  short_name text NOT NULL,
  address text NOT NULL,
  phone text NOT NULL,
  zalo_url text,
  facebook_url text,
  opening_hours text DEFAULT '09:00 - 21:00',
  is_active boolean DEFAULT true,
  display_order int DEFAULT 0,
  created_at timestamp with time zone DEFAULT timezone('utc'::text, now()) NOT NULL
);

